#!/usr/bin/env node
// Checks that specs and tests stay linked (spec-driven development).
//   - Every test reference [XXX-NN-ACn] must point to a criterion defined in a spec.
//   - Every criterion of an approved or implemented spec must be covered by a real (not todo/skip) test.
// Usage: node workflow/scripts/check-traceability.mjs [--markdown <output.md>]

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const SPEC_DIR = "workflow/specs";
const TEST_DIRS = ["src", "tests", "supabase/tests", "workflow"];
const TEST_FILE = /\.(test|spec)\.(ts|tsx|mjs)$|\.test\.sql$/;
const ENFORCED_STATUSES = new Set(["approved", "implemented"]);
const AC_ID = /[A-Z]{2,3}-\d{2}-AC\d+/;

/** Parses one spec file into { id, status, criteria } or returns an error string. */
export function parseSpec(text, file) {
  const frontMatter = text.match(/^---\n([\s\S]*?)\n---/);
  if (!frontMatter) return { error: `${file}: missing front matter` };

  const fields = Object.fromEntries(
    frontMatter[1].split("\n").map((line) => line.split(/:\s*/, 2).map((part) => part.trim())),
  );
  if (!fields.id || !fields.status) return { error: `${file}: front matter needs id and status` };

  const definition = new RegExp(`^\\s*-\\s+\\*\\*(${fields.id}-AC\\d+)\\*\\*`, "gm");
  const criteria = [...text.matchAll(definition)].map((match) => match[1]);
  return { id: fields.id, status: fields.status, file, criteria };
}

/** Finds [XXX-NN-ACn] references; references on todo/skip lines count as pending, not covered. */
export function findReferences(text, file) {
  return text.split("\n").flatMap((line, index) =>
    [...line.matchAll(new RegExp(`\\[(${AC_ID.source})\\]`, "g"))].map((match) => ({
      id: match[1],
      location: `${file}:${index + 1}`,
      pending: /\.(todo|skip)\(/.test(line),
    })),
  );
}

/** Compares specs with references and returns { errors, warnings, rows }. */
export function checkTraceability(specs, references) {
  const errors = [];
  const warnings = [];
  const defined = new Map();

  for (const spec of specs) {
    for (const criterion of spec.criteria) defined.set(criterion, spec);
  }

  for (const ref of references) {
    if (!defined.has(ref.id))
      errors.push(`${ref.location}: references unknown criterion ${ref.id}`);
  }

  const rows = [];
  for (const spec of specs) {
    for (const criterion of spec.criteria) {
      const covering = references.filter((ref) => ref.id === criterion && !ref.pending);
      rows.push({ criterion, status: spec.status, tests: covering.map((ref) => ref.location) });
      if (covering.length > 0) continue;
      const message = `${criterion} (${spec.status}) has no test`;
      if (ENFORCED_STATUSES.has(spec.status)) errors.push(message);
      else warnings.push(message);
    }
  }
  return { errors, warnings, rows };
}

function listFiles(dir, pattern) {
  try {
    return readdirSync(dir, { recursive: true })
      .map((entry) => path.join(dir, entry))
      .filter((file) => !file.includes("node_modules") && pattern.test(file));
  } catch {
    return [];
  }
}

function toMarkdown(rows) {
  const lines = ["| Criterion | Spec status | Covered by |", "| --- | --- | --- |"];
  for (const row of rows) {
    lines.push(`| ${row.criterion} | ${row.status} | ${row.tests.join("<br>") || "**none**"} |`);
  }
  return `# Traceability matrix\n\nGenerated by \`npm run check:spec\`.\n\n${lines.join("\n")}\n`;
}

function main() {
  const specFiles = listFiles(SPEC_DIR, /\.md$/).filter(
    (file) => !path.basename(file).startsWith("_"),
  );
  const parsed = specFiles.map((file) => parseSpec(readFileSync(file, "utf8"), file));
  const specs = parsed.filter((spec) => !spec.error);
  const references = TEST_DIRS.flatMap((dir) => listFiles(dir, TEST_FILE)).flatMap((file) =>
    path.basename(file) === "check-traceability.test.mjs" || file.replaceAll("\\", "/").startsWith("workflow/evaluation/")
      ? []
      : findReferences(readFileSync(file, "utf8"), file),
  );

  const { errors, warnings, rows } = checkTraceability(specs, references);
  errors.unshift(...parsed.filter((spec) => spec.error).map((spec) => spec.error));

  const markdownFlag = process.argv.indexOf("--markdown");
  if (markdownFlag !== -1) writeFileSync(process.argv[markdownFlag + 1], toMarkdown(rows));

  const covered = rows.filter((row) => row.tests.length > 0).length;
  console.log(`Specs: ${specs.length}  Criteria: ${rows.length}  Covered: ${covered}`);
  warnings.forEach((warning) => console.log(`warning: ${warning}`));
  errors.forEach((error) => console.error(`error: ${error}`));
  process.exitCode = errors.length > 0 ? 1 : 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
